// Function to get questions by category
export function getQuestionsByCategory(category) {
  return QUIZ_QUESTIONS.filter(q => q.category === category);
}

// Function to get a random mix of questions
export function getRandomMixedQuestions(count = 7) {
  const categories = ['Sweden', 'NHL Hockey', 'EU Politics', 'Aviation', 'Automotive Industry', 'Space Exploration', 'Staffan Personal'];
  const questionsPerCategory = Math.floor(count / categories.length);
  const remainder = count % categories.length;
  
  let selectedQuestions = [];
  
  categories.forEach((category, index) => {
    const categoryQuestions = getQuestionsByCategory(category);
    const numToSelect = questionsPerCategory + (index < remainder ? 1 : 0);
    
    // Shuffle and select questions from this category
    const shuffled = categoryQuestions.sort(() => 0.5 - Math.random());
    selectedQuestions.push(...shuffled.slice(0, numToSelect));
  });
  
  // Final shuffle of all selected questions
  return selectedQuestions.sort(() => 0.5 - Math.random());
}

// Function to get all categories
export function getCategories() {
  return [...new Set(QUIZ_QUESTIONS.map(q => q.category))];
}

// Function to get question count by category
export function getQuestionCountByCategory() {
  const categories = getCategories();
  const counts = {};
  
  categories.forEach(category => {
    counts[category] = getQuestionsByCategory(category).length;
  });
  
  return counts;
}
